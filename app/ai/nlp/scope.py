"""Отказывает просьбам вне продукта ассистента.

Короткий список фраз ловит очевидные попытки до вызова модели; остальное закрывает
промпт, где та же граница описана словами.
"""

from __future__ import annotations

OFF_TOPIC_REPLY = (
    "Я помогаю только с задачами, встречами и напоминаниями. "
    "Скажите, что запланировать, — например: «Напомни завтра в 10 позвонить Ивану»."
)

_OFF_TOPIC = (
    "дай рецепт",
    "расскажи рецепт",
    "как приготовить",
    "как испечь",
    "расскажи анекдот",
    "расскажи стих",
    "напиши стих",
    "напиши код",
    "напиши программу",
    "переведи ",
)
_INJECTION = (
    "игнорируй инструкции",
    "игнорируй все инструкции",
    "забудь инструкции",
    "system prompt",
    "системный промпт",
    "покажи промпт",
    "твои инструкции",
    "твои правила",
)


def normalize(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def is_off_topic(text: str) -> bool:
    normalized = normalize(text)
    return any(phrase in normalized for phrase in _OFF_TOPIC + _INJECTION)
